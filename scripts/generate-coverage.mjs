import { readFile, writeFile } from 'node:fs/promises';

async function readJson(file) {
  try {
    return JSON.parse(await readFile(file, 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') return undefined;
    throw error;
  }
}
const namespaces = await readJson('tests/e2e/namespaces.json');
const report = await readJson('reports/cucumber.json');
const extension = await readJson('reports/extension.json');
const browser = await readJson('coverage/browser/coverage-summary.json');
const scenarios = (report ?? []).flatMap((feature) =>
  (feature.elements ?? [])
    .filter((item) => item.type === 'scenario')
    .map((item) => {
      const tags = [...(feature.tags ?? []), ...(item.tags ?? [])].map((tag) => tag.name.slice(1));
      const statuses = [...(item.before ?? []), ...(item.steps ?? []), ...(item.after ?? [])].map(
        (step) => step.result?.status,
      );
      const status =
        statuses.length && statuses.every((value) => value === 'passed')
          ? 'passed'
          : statuses.includes('failed')
            ? 'failed'
            : 'incomplete';
      return { name: item.name, tags, status };
    }),
);
for (const scenario of scenarios) {
  const namespace = scenario.tags.find((tag) => tag.startsWith('namespace:'))?.slice(10);
  if (!namespace || !(namespace in namespaces))
    throw new Error(`Unregistered feature namespace: ${scenario.name}`);
}
const passed = scenarios.filter((scenario) => scenario.status === 'passed').length;
const lines = [
  '# Coverage',
  '',
  'Generated by `pnpm coverage:generate`. Browser percentages cover preference infrastructure only; component behavior is covered through journeys, never component unit tests.',
  '',
  `Cucumber: ${report ? `${passed}/${scenarios.length} scenarios passed` : 'not run'}. Extension Playwright: ${extension ? `${extension.stats.expected} passed, ${extension.stats.unexpected} failed` : 'not run'}.`,
  '',
  '## System Journey Graph',
  '',
  'Edges come from scenario transition tags. An edge is verified only when all scenarios declaring it passed.',
  '',
  '```mermaid',
  'flowchart LR',
];
const edges = new Map();
for (const scenario of scenarios)
  for (const tag of scenario.tags.filter((tag) => tag.startsWith('transition:'))) {
    const edge = tag.slice(11);
    const results = edges.get(edge) ?? [];
    results.push(scenario.status);
    edges.set(edge, results);
  }
if (!edges.size) lines.push('  not_run["Journeys not run"]');
for (const [edge, results] of edges) {
  const [from, to] = edge.split('>');
  if (!from || !to || !/^[a-z-]+$/.test(from + to)) throw new Error(`Invalid transition: ${edge}`);
  lines.push(
    `  ${from.replaceAll('-', '_')} -->|"${results.every((value) => value === 'passed') ? 'verified' : 'unverified'}"| ${to.replaceAll('-', '_')}`,
  );
}
lines.push(
  '```',
  '',
  '## State-Fusion Matrix',
  '',
  'Rows record states asserted together in one executed scenario; this is observed coverage, not an exhaustive Cartesian-product claim.',
  '',
  '| Journey | Mood | Name | Ambient | Reduce Motion | Validation | Recovery | Intro | Result |',
  '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
);
for (const scenario of scenarios) {
  const cells = [
    'mood',
    'name',
    'ambient',
    'reduced-motion',
    'validation',
    'recovery',
    'intro',
  ].map((state) => (scenario.tags.includes(`state:${state}`) ? '✓' : '—'));
  lines.push(
    `| ${scenario.name.replaceAll('|', '\\|')} | ${cells.join(' | ')} | ${scenario.status} |`,
  );
}
if (!scenarios.length) lines.push('| Not run | — | — | — | — | — | — | — | not run |');
lines.push(
  '',
  '## Feature Namespace Disposition',
  '',
  '| Namespace | Disposition | Owner | Evidence | Scope |',
  '| --- | --- | --- | --- | --- |',
);
for (const [name, entry] of Object.entries(namespaces)) {
  const matching = scenarios.filter((scenario) => scenario.tags.includes(`namespace:${name}`));
  const evidence =
    name === 'extension'
      ? extension
        ? `${extension.stats.expected} passed`
        : 'not run'
      : matching.length
        ? `${matching.filter((scenario) => scenario.status === 'passed').length}/${matching.length} passed`
        : 'not run';
  lines.push(
    `| ${name} | ${entry.disposition} | [${entry.owner}](./${entry.owner}) | ${evidence} | ${entry.reason} |`,
  );
}
lines.push('', '## Browser Infrastructure Coverage', '', '| Metric | Percent |', '| --- | --- |');
for (const metric of ['statements', 'branches', 'functions', 'lines'])
  lines.push(`| ${metric} | ${browser ? `${browser.total[metric].pct}%` : 'not run'} |`);
lines.push(
  '',
  'Raw reports: `reports/cucumber.json`, `reports/extension.json`, and `coverage/browser/coverage-summary.json`. Missing reports are never counted as passing.',
  '',
);
await writeFile('COVERAGE.md', lines.join('\n'));
console.log(`COVERAGE.md generated (${passed}/${scenarios.length} Cucumber scenarios passed).`);
